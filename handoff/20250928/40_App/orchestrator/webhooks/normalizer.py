def _title_is_non_actionable(title: str) -> bool:
    """
    Check if a PR title indicates non-actionable changes.

    Smart PR Filtering (Dec 2025)
    PRs with titles starting with chore/ci/test/docs/style are considered
    non-actionable for docs generation purposes.

    Args:
        title: The PR title string

    Returns:
        True if the title indicates non-actionable changes (should skip)
    """
    if not title:
        return False

    title_lower = title.lower().strip()
    return title_lower.startswith(SKIP_TITLE_PREFIXES)


def _path_is_non_code(path: str) -> bool:
    """
    Check if a file path is a non-code file (config/docs/tests/CI).

    Smart PR Filtering (Dec 2025)
    Files matching these patterns are considered non-code changes.

    Args:
        path: The file path string

    Returns:
        True if the path is a non-code file
    """
    if not path:
        return True  # Empty/invalid path treated as non-code for safety (fail-open)

    # Normalize path separators for cross-platform robustness
    # GitHub API always uses forward slashes, but this makes the helper reusable
    path_lower = path.lower().replace("\\", "/")
    filename = path_lower.split("/")[-1]

    # Check exact filename matches
    if filename in SKIP_FILE_PATTERNS["filenames"]:
        return True

    # Check file extension
    ext = ""
    if "." in filename:
        ext = "." + filename.rsplit(".", 1)[-1]
    if ext in SKIP_FILE_PATTERNS["extensions"]:
        return True
    if ext in SKIP_FILE_PATTERNS["doc_extensions"]:
        return True

    # Check path prefixes
    for prefix in SKIP_FILE_PATTERNS["path_prefixes"]:
        if path_lower.startswith(prefix):
            return True

    # Check test file suffixes
    for suffix in SKIP_FILE_PATTERNS["test_suffixes"]:
        if path_lower.endswith(suffix):
            return True

    return False


def _should_skip_by_paths(file_paths: list) -> tuple:
    """
    Check if all changed files are non-code files.

    Smart PR Filtering (Dec 2025)
    If a PR ONLY modifies config/docs/tests/CI files, skip docs generation.

    Args:
        file_paths: List of changed file paths

    Returns:
        Tuple of (should_skip: bool, reason: str, sample_paths: list)
    """
    if not file_paths:
        # No files = skip (nothing to document)
        return True, "no_files", []

    non_code_paths = []
    code_paths = []

    for path in file_paths:
        if _path_is_non_code(path):
            non_code_paths.append(path)
        else:
            code_paths.append(path)
            # Early exit: found a code file, no need to check more
            if len(code_paths) >= 1:
                return False, "has_code_files", code_paths[:3]

    # All files are non-code
    return True, "only_non_code_files", non_code_paths[:5]


def _get_pr_files_from_api(repo: str, pr_number: int) -> tuple:
    """
    Fetch PR changed files from GitHub API.

    Smart PR Filtering (Dec 2025)
    This function fetches the list of changed files for a PR.
    It handles pagination and rate limiting gracefully.

    Args:
        repo: Repository in owner/repo format
        pr_number: Pull request number

    Returns:
        Tuple of (file_paths: list, error: str or None)
    """
    try:
        from tools.github_api import get_repo
        github_repo = get_repo()
        if not github_repo:
            return [], "repo_not_available"

        pr = github_repo.get_pull(pr_number)
        # get_files() returns a paginated list, iterate to get all
        file_paths = []
        for f in pr.get_files():
            file_paths.append(f.filename)
            # Early exit optimization: if we find a code file, we can stop
            # Return all files seen so far for debugging context
            if not _path_is_non_code(f.filename):
                return file_paths, None
        return file_paths, None
    except Exception as e:
        logger.warning(
            "[SmartFilter] Failed to fetch PR files from API",
            extra={
                "operation": "smart_filter_api_error",
                "repo": repo,
                "pr_number": pr_number,
                "error": str(e)[:200],
            }
        )
        return [], f"api_error: {str(e)[:100]}"


def should_skip_pr_by_smart_filters(event: "WebhookEvent") -> tuple:
    """
    Check if a PR event should be skipped based on smart filtering rules.

    Smart PR Filtering (Dec 2025)
    This function applies content-based and semantic filtering to determine
    if a PR is "worth documenting". It's separate from the orchestrator
    self-loop prevention layer.

    Filter Pipeline:
    1. Semantic title filter (cheap, runs first)
    2. File path filter (requires API call, runs only if title passes)

    Args:
        event: The webhook event to check

    Returns:
        Tuple of (should_skip: bool, reason: str, details: dict)
    """
    # Only apply to PR events
    pr_event_types = {
        WebhookEventType.PR_OPENED,
        WebhookEventType.PR_MERGED,
    }
    if event.event_type not in pr_event_types:
        return False, "not_pr_event", {}

    repo = f"{event.repo_owner}/{event.repo_name}" if event.repo_owner and event.repo_name else "unknown"
    pr_number = event.resource_id
    title = event.title or ""

    # Filter 1: Semantic title filter (cheap, runs first)
    if _title_is_non_actionable(title):
        logger.info(
            "[SmartFilter] Skipping PR by semantic title filter",
            extra={
                "operation": "pr_event_skip_semantic_title",
                "event_id": event.event_id,
                "repo": repo,
                "pr_number": pr_number,
                "title": title[:100],
                "reason": "non_actionable_title_prefix",
            }
        )
        return True, "semantic_title_skip", {"title_prefix": title.split(":")[0] if ":" in title else title[:20]}

    # Filter 2: File path filter (requires API call)
    # Only fetch files if title didn't trigger skip
    try:
        pr_number_int = int(pr_number) if pr_number else 0
    except (ValueError, TypeError):
        pr_number_int = 0

    if pr_number_int > 0:
        file_paths, api_error = _get_pr_files_from_api(repo, pr_number_int)

        if api_error:
            # API error: fail open (don't skip, let the PR be processed)
            logger.warning(
                "[SmartFilter] API error fetching PR files, failing open",
                extra={
                    "operation": "smart_filter_api_fail_open",
                    "event_id": event.event_id,
                    "repo": repo,
                    "pr_number": pr_number_int,
                    "error": api_error,
                }
            )
            return False, "api_error_fail_open", {"error": api_error}

        should_skip, reason, sample_paths = _should_skip_by_paths(file_paths)

        if should_skip:
            logger.info(
                "[SmartFilter] Skipping PR by file path filter",
                extra={
                    "operation": "pr_event_skip_file_paths_only",
                    "event_id": event.event_id,
                    "repo": repo,
                    "pr_number": pr_number_int,
                    "reason": reason,
                    "file_count": len(file_paths),
                    "sample_paths": sample_paths,
                }
            )
            return True, f"file_path_skip:{reason}", {"file_count": len(file_paths), "sample_paths": sample_paths}

    return False, "passed_all_filters", {}


def is_internal_repo_allowed(repo: str) -> bool:
    """
    Check if an internal repo is allowed for AI review in Staging.

    Phase B-B: Internal Repo Dogfooding
    This enables MorningAI to review its own code in Staging environment.

    Preconditions (all must be true):
    1. settings object is available
    2. allow_internal_repos_in_staging is True
    3. is_staging environment is True
    4. repo is in internal_repos_whitelist

    Args:
        repo: Repository in owner/repo format (e.g., 'RC918/morningai')

    Returns:
        True if the repo is an internal repo and dogfooding is enabled in Staging
    """
    if not settings:
        return False

    # Gather all preconditions using getattr for robustness
    is_staging_env = getattr(settings, 'is_staging', False)
    allow_internal = getattr(settings, 'allow_internal_repos_in_staging', False)
    whitelist_str = getattr(settings, 'internal_repos_whitelist', '')

    # Dogfooding is only allowed when all preconditions are met
    if not (allow_internal and is_staging_env and whitelist_str):
        return False

    # Parse whitelist and check if repo is allowed
    whitelist = {r.strip() for r in whitelist_str.split(',') if r.strip()}
    is_allowed = repo in whitelist

    if is_allowed:
        logger.info(
            "[EventNormalizer] Internal repo allowed for AI review (dogfooding)",
            extra={
                "operation": "internal_repo_dogfooding",
                "repo": repo,
                "is_staging": is_staging_env,
            }
        )

    return is_allowed


@dataclass
class PRUpdatedAllowedResult:
    """Result of PR_UPDATED allowed check"""
    is_allowed: bool
    reason: str
    should_schedule_job: bool = False
    job_token: Optional[str] = None
    debounce_seconds: int = 30


def is_pr_updated_allowed(repo: str, pr_number: int, redis_url: str = None) -> PRUpdatedAllowedResult:
    """
    Check if a PR_UPDATED event should trigger a delayed review job.

    Phase B-B: PR_UPDATED Event Support with Debounce/Throttle
    This enables AI review on PR updates (push events) with cost protection.

    CRITICAL FIX: Now returns should_schedule_job=True for first event,
    allowing caller to enqueue a delayed job that sleeps then processes.

    Preconditions (all must be true):
    1. settings.enable_pr_updated_review is True
    2. repo is in pr_updated_repos_whitelist (or whitelist is empty = all repos)
    3. Debounce check passes (first event or debounce window expired)
    4. Throttle check passes (not reviewed too recently)

    Args:
        repo: Repository in owner/repo format (e.g., 'RC918/morningai')
        pr_number: Pull request number
        redis_url: Optional Redis URL for debounce/throttle tracking

    Returns:
        PRUpdatedAllowedResult with:
        - is_allowed: True if event should trigger review workflow
        - should_schedule_job: True if caller should enqueue delayed job
        - job_token: Token to pass to delayed job for verification
        - debounce_seconds: Debounce window for delayed job sleep
        - reason: Human-readable explanation
    """
    if not settings:
        return PRUpdatedAllowedResult(
            is_allowed=False,
            reason="settings_unavailable",
        )

    enable_pr_updated = getattr(settings, 'enable_pr_updated_review', False)
    if not enable_pr_updated:
        return PRUpdatedAllowedResult(
            is_allowed=False,
            reason="pr_updated_review_disabled",
        )

    whitelist_str = getattr(settings, 'pr_updated_repos_whitelist', '')
    if whitelist_str:
        whitelist = {r.strip() for r in whitelist_str.split(',') if r.strip()}
        if repo not in whitelist:
            return PRUpdatedAllowedResult(
                is_allowed=False,
                reason="repo_not_in_whitelist",
            )

    debounce_seconds = getattr(settings, 'pr_updated_debounce_seconds', 30)
    throttle_seconds = getattr(settings, 'pr_updated_throttle_seconds', 600)

    debounce_result = check_pr_updated_debounce(
        repo=repo,
        pr_number=pr_number,
        debounce_seconds=debounce_seconds,
        throttle_seconds=throttle_seconds,
        redis_url=redis_url,
    )

    if debounce_result.should_schedule_job:
        logger.info(
            "[EventNormalizer] PR_UPDATED event - scheduling delayed job",
            extra={
                "operation": "pr_updated_schedule_job",
                "repo": repo,
                "pr_number": pr_number,
                "job_token": debounce_result.job_token,
                "debounce_seconds": debounce_seconds,
            }
        )
        return PRUpdatedAllowedResult(
            is_allowed=True,
            reason="first_event: delayed job scheduled",
            should_schedule_job=True,
            job_token=debounce_result.job_token,
            debounce_seconds=debounce_seconds,
        )

    logger.info(
        "[EventNormalizer] PR_UPDATED event debounced/throttled",
        extra={
            "operation": "pr_updated_debounce_check",
            "repo": repo,
            "pr_number": pr_number,
            "reason": debounce_result.reason,
        }
    )
    return PRUpdatedAllowedResult(
        is_allowed=False,
        reason=debounce_result.reason,
    )


@dataclass
class NormalizedTask:
    """
    A task extracted from a webhook event, ready for Meta Agent processing.

    This represents the bridge between external events and internal task execution.
    """
    task_id: str
    source_event: WebhookEvent
    goal_text: str
    priority: str
    requires_approval: bool
    context: Dict[str, Any] = field(default_factory=dict)
    created_at: datetime = field(default_factory=datetime.now)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for serialization"""
