def is_self_generated_review(event: "WebhookEvent") -> bool:
    """
    Check if a PR_REVIEWED event was generated by our own orchestrator.

    Issue: Self-Trigger Loop Prevention
    When the orchestrator posts a review to GitHub, GitHub sends a PR_REVIEWED
    webhook back. Without this check, the orchestrator would process its own
    review as a new event, creating an infinite feedback loop.

    The detection works by checking for a hidden HTML comment marker in the
    review body that the orchestrator adds when posting reviews.

    Args:
        event: The webhook event to check

    Returns:
        True if this is a self-generated review that should be skipped
    """
    # Only check PR_REVIEWED events
    if event.event_type != WebhookEventType.PR_REVIEWED:
        return False

    # Check the event description (review body) for our marker
    description = event.description or ""
    if MORNINGAI_REVIEW_MARKER in description:
        logger.info(
            "[EventNormalizer] Detected self-generated review, skipping to prevent feedback loop",
            extra={
                "operation": "self_review_detection",
                "event_id": event.event_id,
                "repo": f"{event.repo_owner}/{event.repo_name}",
                "pr_number": event.resource_id,
            }
        )
        return True

    # Also check raw payload for the marker (in case description is truncated)
    raw_payload = event.raw_payload or {}
    review = raw_payload.get("review", {})
    review_body = review.get("body", "")
    if MORNINGAI_REVIEW_MARKER in review_body:
        logger.info(
            "[EventNormalizer] Detected self-generated review (from raw payload), skipping",
            extra={
                "operation": "self_review_detection",
                "event_id": event.event_id,
                "repo": f"{event.repo_owner}/{event.repo_name}",
                "pr_number": event.resource_id,
            }
        )
        return True

    return False


def _extract_head_branch_from_payload(raw_payload: dict) -> str:
    """
    Extract head branch from various GitHub webhook payload structures.

    Issue: Staging Observation (#3047) - Consolidated branch extraction
    This helper unifies branch extraction logic used in multiple places:
    - should_skip_orchestrator_pr_event() for orchestrator branch detection
    - is_actionable() UNKNOWN event logging for staging observation

    Supported payload structures:
    - PR events: pull_request.head.ref
    - Check suite events: check_suite.head_branch or check_suite.pull_requests[0].head.ref
    - Check run events: check_run.check_suite.head_branch
    - Status events: branches[0].name

    Args:
        raw_payload: The raw webhook payload dict

    Returns:
        The head branch name, or empty string if not found
    """
    if not isinstance(raw_payload, dict):
        return ""

    head_ref = ""

    # Try PR payload first (most common for PR events)
    pr_data = raw_payload.get("pull_request", {})
    if pr_data and isinstance(pr_data, dict):
        head_data = pr_data.get("head", {})
        if isinstance(head_data, dict):
            head_ref = head_data.get("ref", "")

    # Try check_suite payload (CI events)
    if not head_ref:
        check_suite = raw_payload.get("check_suite", {})
        if check_suite and isinstance(check_suite, dict):
            head_ref = check_suite.get("head_branch", "")
            # Also check pull_requests array in check_suite
            if not head_ref:
                prs = check_suite.get("pull_requests", [])
                if prs and isinstance(prs, list) and len(prs) > 0:
                    first_pr = prs[0]
                    if isinstance(first_pr, dict):
                        head_data = first_pr.get("head", {})
                        if isinstance(head_data, dict):
                            head_ref = head_data.get("ref", "")

    # Try check_run payload (CI events)
    if not head_ref:
        check_run = raw_payload.get("check_run", {})
        if check_run and isinstance(check_run, dict):
            check_suite_in_run = check_run.get("check_suite", {})
            if isinstance(check_suite_in_run, dict):
                head_ref = check_suite_in_run.get("head_branch", "")

    # Try status event payload
    if not head_ref:
        branches = raw_payload.get("branches", [])
        if branches and isinstance(branches, list) and len(branches) > 0:
            first_branch = branches[0]
            if isinstance(first_branch, dict):
                head_ref = first_branch.get("name", "")

    # Ensure we return a string
    if not isinstance(head_ref, str):
        head_ref = ""

    return head_ref


def should_skip_orchestrator_pr_event(event: "WebhookEvent") -> bool:
    """
    Check if a PR event should be skipped because it's from an orchestrator-generated PR.

    Issue: Self-Trigger Loop Prevention (Dec 2025)
    Issue: Garbage PR Fix - Defense in Depth (Dec 2025)

    When the orchestrator creates a docs PR, GitHub sends PR webhooks back.
    Without this check, the orchestrator would process its own PR events and
    create more docs PRs, causing an infinite self-trigger loop.

    Detection methods (any match triggers skip):
    1. Branch prefix: orchestrator/* branches
    2. Label filter: PRs with 'orchestrator-docs' or 'orchestrator-docs-test' labels

    Defense in Depth (Dec 2025):
    This function also checks UNKNOWN events, which may be CI events (check_suite,
    check_run, status) that reference orchestrator PRs. Combined with the UNKNOWN
    event filter in is_actionable(), this provides layered protection.

    This is a zero-cost check that uses only the webhook payload data.

    Args:
        event: The webhook event to check

    Returns:
        True if this is an orchestrator-generated PR that should be skipped
    """
    # Only check PR-related events and UNKNOWN events (which may be CI events)
    # Issue: Garbage PR Fix - UNKNOWN events can be check_suite/check_run/status
    # that reference orchestrator PRs and should be filtered
    pr_event_types = {
        WebhookEventType.PR_OPENED,
        WebhookEventType.PR_CLOSED,
        WebhookEventType.PR_MERGED,
        WebhookEventType.PR_UPDATED,
        WebhookEventType.PR_REVIEWED,
        WebhookEventType.UNKNOWN,  # CI events parsed as UNKNOWN
    }
    if event.event_type not in pr_event_types:
        return False

    repo = f"{event.repo_owner}/{event.repo_name}" if event.repo_owner and event.repo_name else "unknown"

    # Extract head branch using consolidated helper function
    # See _extract_head_branch_from_payload() for supported payload structures
    raw_payload = event.raw_payload or {}
    head_ref = _extract_head_branch_from_payload(raw_payload)

    # Check 1: Label filter - skip PRs with orchestrator-docs labels
    # This catches PRs created by any actor (including Devin) that have the orchestrator label
    # Import constants from utils/constants.py to ensure single source of truth
    from utils.constants import LABEL_ORCHESTRATOR_DOCS, LABEL_ORCHESTRATOR_DOCS_TEST
    orchestrator_labels = {LABEL_ORCHESTRATOR_DOCS.lower(), LABEL_ORCHESTRATOR_DOCS_TEST.lower()}

    # Type guard: filter out non-string labels to prevent AttributeError on .lower()
    # GitHub handler may produce None values if label.get("name") returns None
    event_labels_raw = event.labels if isinstance(event.labels, list) else []
    event_labels = set()
    for label in event_labels_raw:
        if isinstance(label, str):
            event_labels.add(label.lower())
        else:
            # Log warning for unexpected label type
            logger.warning(
                "[EventNormalizer] Unexpected label type in event",
                extra={
                    "operation": "label_type_warning",
                    "event_id": event.event_id,
                    "label_type": type(label).__name__,
                    "label_value": str(label)[:100],
                }
            )

    matched_labels = orchestrator_labels & event_labels

    # Staging observation (#3047) - capture GitHub event metadata for log analysis
    metadata = event.metadata or {}
    github_event = metadata.get("github_event", "unknown")
    github_action = metadata.get("action", "unknown")

    if matched_labels:
        logger.info(
            "[EventNormalizer] Skipping orchestrator-generated event (label match)",
            extra={
                "operation": "orchestrator_event_skip",
                "event_id": event.event_id,
                "repo": repo,
                "resource_id": event.resource_id,
                "head_ref": head_ref,
                "matched_labels": list(matched_labels),
                "event_type": event.event_type.value,
                "github_event": github_event,
                "github_action": github_action,
                "actor": event.actor_name or "unknown",
                "reason": "orchestrator_label_match",
            }
        )
        return True

    # Check 2: Branch prefix - skip events from orchestrator/* branches
    # This catches PR events, CI events (check_suite, check_run), and status events
    if head_ref.startswith("orchestrator/"):
        logger.info(
            "[EventNormalizer] Skipping orchestrator-generated event (branch match)",
            extra={
                "operation": "orchestrator_event_skip",
                "event_id": event.event_id,
                "repo": repo,
                "resource_id": event.resource_id,
                "head_ref": head_ref,
                "event_type": event.event_type.value,
                "github_event": github_event,
                "github_action": github_action,
                "actor": event.actor_name or "unknown",
                "reason": "orchestrator_branch_prefix",
            }
        )
        return True

    return False


